/**
 * Minimal two-language dictionary. No dependency, no runtime fetch: the locale is
 * a cookie read on the server and passed to a client context, so server and client
 * render the same strings and there is no hydration mismatch.
 */
export const LOCALES = ["en", "zh"] as const;
export type Locale = (typeof LOCALES)[number];
export const LOCALE_COOKIE = "tapeci_locale";
export const DEFAULT_LOCALE: Locale = "en";

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "zh";
}

export function parseLocale(value: string | undefined | null): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

